import AppKit
import Combine

/// Watches the clipboard, converts rich text to plain text, keeps history, skips secrets.
@MainActor
final class ClipboardManager: ObservableObject {
    static let shared = ClipboardManager()

    @Published private(set) var items: [ClipboardItem] = []
    @Published private(set) var currentText: String = ""

    var suspendTracking = false
    private var lastChangeCount = NSPasteboard.general.changeCount
    private var timer: Timer?
    private var cancellable: AnyCancellable?

    private static let passwordManagers: Set<String> = [
        "com.agilebits.onepassword7", "com.1password.1password", "com.agilebits.onepassword-osx",
        "com.bitwarden.desktop", "com.apple.keychainaccess", "com.apple.Passwords",
        "com.lastpass.LastPass", "com.dashlane.dashlanephonefinal", "com.dashlane.Dashlane",
        "org.keepassxc.keepassxc", "com.keepassium.mac", "com.enpass.Enpass", "com.nordpass.macos.NordPass",
        "com.roboform.mac", "com.keepersecurity.passwordmanager", "in.sinew.Enpass-Desktop",
    ]
    private static let secretTypes: [NSPasteboard.PasteboardType] = [
        .init("org.nspasteboard.ConcealedType"), .init("org.nspasteboard.TransientType"),
        .init("org.nspasteboard.AutoGeneratedType"), .init("com.agilebits.onepassword"),
    ]

    private var fileURL: URL { SettingsStore.supportDir.appendingPathComponent("history.json") }

    func start() {
        load()
        currentText = readPasteboard() ?? items.first?.text ?? ""
        restartTimer()
        cancellable = SettingsStore.didChange.receive(on: DispatchQueue.main).sink { [weak self] key in
            if key == K.pollInterval || key == "*" { self?.restartTimer() }
            if key == K.historySize || key == "*" { self?.trim(); self?.save() }
        }
    }

    private func restartTimer() {
        timer?.invalidate()
        let interval = max(0.1, SettingsStore.shared.num(K.pollInterval) / 1000)
        timer = Timer.scheduledTimer(withTimeInterval: interval, repeats: true) { [weak self] _ in
            MainActor.assumeIsolated { self?.poll() }
        }
    }

    func ignoreCurrentChangeCount() { lastChangeCount = NSPasteboard.general.changeCount }

    func poll() {
        let pb = NSPasteboard.general
        guard pb.changeCount != lastChangeCount else { return }
        lastChangeCount = pb.changeCount
        guard !suspendTracking else { return }
        let s = SettingsStore.shared
        let types = pb.types ?? []
        if s.bool(K.skipConcealed) && types.contains(where: { Self.secretTypes.contains($0) }) { return }
        let front = NSWorkspace.shared.frontmostApplication
        if s.bool(K.skipPasswordManagers), let bid = front?.bundleIdentifier, Self.passwordManagers.contains(bid) { return }
        guard let text = readPasteboard() else { return }
        currentText = text
        add(text, source: front?.localizedName)
    }

    /// Plain text from the clipboard. Rich text is flattened. Images/files are ignored.
    func readPasteboard() -> String? {
        let pb = NSPasteboard.general
        let types = pb.types ?? []
        var text: String?
        if let s = pb.string(forType: .string) { text = s }
        else if let d = pb.data(forType: .rtf), let a = NSAttributedString(rtf: d, documentAttributes: nil) { text = a.string }
        else if let d = pb.data(forType: .rtfd), let a = NSAttributedString(rtfd: d, documentAttributes: nil) { text = a.string }
        else if let d = pb.data(forType: .html),
                let a = try? NSAttributedString(data: d, options: [.documentType: NSAttributedString.DocumentType.html,
                                                                   .characterEncoding: String.Encoding.utf8.rawValue],
                                                documentAttributes: nil) { text = a.string }
        // A copied file in Finder gives a filename string plus a file URL; skip those.
        if types.contains(.fileURL) && !types.contains(.rtf) && !types.contains(.html) { return nil }
        guard let t = text?.replacingOccurrences(of: "\u{FFFC}", with: ""), !t.isEmpty else { return nil }
        let s = SettingsStore.shared
        if t.count < s.int(K.minLength) || t.count > s.int(K.maxItemLength) { return nil }
        return t
    }

    // MARK: History

    private func add(_ text: String, source: String?) {
        let s = SettingsStore.shared
        if s.bool(K.ignoreDuplicates), let idx = items.firstIndex(where: { $0.text == text }) {
            var item = items.remove(at: idx)
            item.date = Date()
            items.insert(item, at: 0)
        } else {
            items.insert(ClipboardItem(text: text, sourceApp: source), at: 0)
        }
        trim()
        save()
    }

    private func trim() {
        let limit = max(1, SettingsStore.shared.int(K.historySize))
        var unpinnedSeen = 0
        items = items.filter { item in
            if item.pinned && SettingsStore.shared.bool(K.pinsEnabled) { return true }
            unpinnedSeen += 1
            return unpinnedSeen <= limit
        }
    }

    /// Make a history item the current clipboard (does not start typing).
    func select(_ item: ClipboardItem) {
        write(item.text)
        if let idx = items.firstIndex(where: { $0.id == item.id }) {
            var it = items.remove(at: idx)
            it.date = Date()
            items.insert(it, at: 0)
        }
        save()
    }

    func update(_ item: ClipboardItem, text: String) {
        guard let idx = items.firstIndex(where: { $0.id == item.id }) else { return }
        let wasCurrent = items[idx].text == currentText
        items[idx].text = text
        if wasCurrent { write(text) }
        save()
    }

    func togglePin(_ item: ClipboardItem) {
        guard let idx = items.firstIndex(where: { $0.id == item.id }) else { return }
        items[idx].pinned.toggle()
        trim()
        save()
    }

    func delete(_ item: ClipboardItem) {
        items.removeAll { $0.id == item.id }
        save()
    }

    func clearHistory(keepPinned: Bool = true) {
        items = keepPinned ? items.filter(\.pinned) : []
        save()
    }

    private func write(_ text: String) {
        let pb = NSPasteboard.general
        pb.clearContents()
        pb.setString(text, forType: .string)
        lastChangeCount = pb.changeCount
        currentText = text
    }

    // MARK: Test hooks
    func _testSnapshot() -> [ClipboardItem] { items }
    func _testRestore(_ list: [ClipboardItem], current: String) { items = list; currentText = current; save() }
    func _testAdd(_ text: String) { add(text, source: "Test") }

    // MARK: Persistence

    private func load() {
        guard let d = try? Data(contentsOf: fileURL),
              let list = try? JSONDecoder().decode([ClipboardItem].self, from: d) else { return }
        items = list
    }

    func save() {
        if let d = try? JSONEncoder().encode(items) { try? d.write(to: fileURL, options: .atomic) }
    }

    func handleQuit() {
        if SettingsStore.shared.bool(K.clearOnQuit) { clearHistory(keepPinned: true) }
        save()
    }
}
